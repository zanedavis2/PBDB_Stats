def aggregate_stats_catching(csv_files):
    # Base numeric columns needed for calculations
    cols_to_keep = ["INN", "PB", "SB", "SB-ATT", "CS"]

    dfs = []
    for name in csv_files:
        file = f"{name}.csv"
        try:
            df = pd.read_csv(file, header=1)  # use header=1 only if CSV has two header lines
            # Adjust the range to include all columns from 148 onwards
            df = df.iloc[:, [1, 2] + list(range(148, df.shape[1]))]
            df.columns = [c.replace(".1", "") for c in df.columns]
            df.columns = [c.replace(".2", "") for c in df.columns]


            # Ensure name columns exist and keep only relevant columns
            if 'Last' not in df.columns:
                df['Last'] = ""
            if 'First' not in df.columns:
                df['First'] = ""

            # Keep only relevant columns that exist
            df = df[[c for c in cols_to_keep + ["Last", "First"] if c in df.columns]]

            # Clean names
            df["Last"] = df["Last"].astype(str).str.strip().str.title()
            df["First"] = df["First"].astype(str).str.strip().str.title()

            # Convert numeric columns
            for col in df.columns:
                if col not in ["Last", "First", "SB-ATT"]: # Exclude SB-ATT from initial conversion
                    df[col] = pd.to_numeric(df[col], errors="coerce").fillna(0)

            dfs.append(df)

        except FileNotFoundError:
            print(f"Warning: File {file} not found. Skipping.")
            continue
        except Exception as e:
            print(f"Warning: Error processing file {file}: {e}. Skipping.")
            continue

    # ===== Combine and aggregate by player =====
    if not dfs:
        return pd.DataFrame(columns=cols_to_keep + ["Last", "First"])

    combined = pd.concat(dfs, ignore_index=True)

    # Ensure "SB-ATT" column exists before splitting
    if "SB-ATT" in combined.columns:
        # Split "SB-ATT" into "SB" and "ATT", handling cases without a hyphen
        split_sb_att = combined["SB-ATT"].astype(str).str.split("-", expand=True)
        if split_sb_att.shape[1] < 2:
             # If expand=True didn't create two columns, add a second NaN column
             split_sb_att[1] = np.nan

        combined["SB"] = pd.to_numeric(split_sb_att[0], errors="coerce").fillna(0).astype(int)
        combined["ATT"] = pd.to_numeric(split_sb_att[1], errors="coerce").fillna(0).astype(int)
    else:
        # Add SB and ATT columns with default 0 if SB-ATT is not present
        combined["SB"] = 0
        combined["ATT"] = 0


    # Group by player and sum all numeric values
    agg_df = (
        combined.groupby(["Last", "First"], as_index=False)
        .sum(numeric_only=True)
    )


    # Convert numeric columns and handle NaNs
    for col in agg_df.columns:
        if col not in ["Last", "First", "INN"]:
            agg_df[col] = agg_df[col].fillna(0).round(0)

    agg_df["CS%"] = np.where(
        agg_df["ATT"] > 0,
        (agg_df["CS"] / agg_df["ATT"] * 100).round(1),
        0
    )
    agg_df["SB-ATT"] = agg_df["SB"].astype(int).astype(str) + "-" + agg_df["ATT"].astype(int).astype(str)
    agg_df = agg_df.drop(columns=["SB", "ATT"])

    return agg_df

