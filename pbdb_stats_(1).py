def aggregate_stats_pitching(csv_files):
    # Base numeric columns needed for calculations
    cols_to_keep = [
        "IP", "ER", "H", "BB", "R", "SO", "K-L", "HR", "#P", "BF", "HBP",
        "FPS%", "FPSO%", "FPSW%", "FPSH%", "S%", "SM%", "LD%", "FB%", "GB%",
        "BABIP", "BA/RISP", "CS", "SB", "SB%", "<3%", "HHB%", "WEAK%", "BBS"
    ]

    dfs = []
    for name in csv_files:
        file = f"{name}.csv"
        df = pd.read_csv(file, header=1)  # use header=1 only if CSV has two header lines
        df = df.iloc[:, [1, 2] + list(range(53, 148))]
        df.columns = [c.replace(".1", "") for c in df.columns]

        # Ensure name columns exist and keep only relevant columns
        if 'Last' not in df.columns:
                df['Last'] = ""
        if 'First' not in df.columns:
                df['First'] = ""

        # Keep only relevant columns that exist
        df = df[[c for c in cols_to_keep + ["Last", "First"] if c in df.columns]]


        # Clean names
        df["Last"] = df["Last"].astype(str).str.strip().str.title()
        df["First"] = df["First"].astype(str).str.strip().str.title()

        # Convert numeric columns
        for col in df.columns:
            if col not in ["Last", "First"]:
                df[col] = pd.to_numeric(df[col], errors="coerce").fillna(0)

 # --- Convert innings format (e.g., 4.2 → 4.6667) ---
        def convert_innings(ip):
            whole = int(ip)
            fraction = round((ip - whole) * 10)
            if fraction == 1:
                return whole + 1/3
            elif fraction == 2:
                return whole + 2/3
            else:
                return ip

        if "IP" in df.columns:
            df["IP"] = df["IP"].apply(convert_innings)


        # ===== Convert percentages to absolute counts =====
        df["Strikes"] = (df["S%"] * df["#P"] / 100).round(0).astype(int)
        df["FirstPitchStrikes"] = (df["FPS%"] * df["BF"] / 100).round(0).astype(int)
        df["FPSO"] = (df["FPSO%"] * df["BF"] / 100).round(0).astype(int)
        df["FPSH"] = (df["FPSH%"] * df["BF"] / 100).round(0).astype(int)

        total_batted_balls = df["BF"] - df["SO"] - df["BB"] - df["HBP"]
        df["GroundBalls"] = (df["GB%"] * total_batted_balls / 100).round(0).astype(int)
        df["FlyBalls"] = (df["FB%"] * total_batted_balls / 100).round(0).astype(int)
        df["LineDrives"] = (df["LD%"] * total_batted_balls / 100).round(0).astype(int)
        df["HardHitBalls"] = (df["HHB%"] * total_batted_balls / 100).round(0).astype(int)
        df["WeakContact"] = (df["WEAK%"] * total_batted_balls / 100).round(0).astype(int)
        df["Under3Pitches"] = (df["<3%"] * df["BF"] / 100).round(0).astype(int)
        df["SwingMisses"] = (df["SM%"] * df["#P"] / 100).round(0).astype(int)

        # Drop original % columns to avoid confusion in later aggregation
        drop_cols = [c for c in df.columns if c.endswith("%")]
        df.drop(columns=drop_cols, inplace=True, errors='ignore')

        dfs.append(df)

    # ===== Combine and aggregate by player =====
    combined = pd.concat(dfs, ignore_index=True)

    # Group by player and sum all numeric values
    agg_df = (
        combined.groupby(["Last", "First"], as_index=False)
        .sum(numeric_only=True)
    )
    # Convert all numeric columns to integers, handling potential NaNs resulting from sum
    for col in agg_df.columns:
        if col not in ["Last", "First"]:
            agg_df[col] = agg_df[col].fillna(0).round(3)


    return agg_df

def generate_aggregated_pitching_df(df):

    columns_to_keep = [
        "Last", "First", "IP", "ERA", "WHIP", "SO", "K-L", "H", "R", "ER", "BB", "BB/INN",
        "FIP", "S%", "FPS%", "FPSO%", "FPSH%", "BAA", "BBS", "SM%", "LD%", "FB%", "GB%",
        "BABIP", "BA/RISP", "CS", "SB", "SB%", "<3%", "HHB%", "WEAK%"
    ]

    df = df.copy()

    # ==== Safety checks ====
    for col in [
        "IP", "ER", "H", "BB", "SO", "K-L", "HR", "#P", "BF", "Strikes", "FirstPitchStrikes",
        "FPSO", "FPSH", "GroundBalls", "FlyBalls", "LineDrives", "HardHitBalls", "WeakContact",
        "Under3Pitches", "SwingMisses", "BBS", "CS", "SB"
    ]:
        if col not in df.columns:
            df[col] = 0

    # Avoid divide-by-zero
    df["IP"] = df["IP"].replace(0, np.nan)
    df["BF"] = df["BF"].replace(0, np.nan)
    df["#P"] = df["#P"].replace(0, np.nan)

    # ==== Derived metrics ====

    # ERA = (ER × 9) / IP
    df["ERA"] = (df["ER"] * 9 / df["IP"]).round(2)

    # WHIP = (BB + H) / IP
    df["WHIP"] = ((df["BB"] + df["H"]) / df["IP"]).round(2)

    # BB/INN = BB / IP
    df["BB/INN"] = (df["BB"] / df["IP"]).round(2)

    # FIP = ((13*HR + 3*BB - 2*K) / IP) + constant
    # Standard constant = 3.1 for normalization
    df["FIP"] = (((13 * df["HR"]) + (3 * df["BB"]) - (2 * df["SO"])) / df["IP"] + 3.1).round(2)

    # Percentages
    df["S%"] = (df["Strikes"] / df["#P"] * 100).round(2)
    df["FPS%"] = (df["FirstPitchStrikes"] / df["BF"] * 100).round(2)
    df["FPSO%"] = (df["FPSO"] / df["BF"] * 100).round(2)
    df["FPSH%"] = (df["FPSH"] / df["BF"] * 100).round(2)
    df["SM%"] = (df["SwingMisses"] / df["#P"] * 100).round(2)
    df["LD%"] = (df["LineDrives"] / (df["BF"]-df["SO"]-df["BB"]-df["HBP"]) * 100).round(2)
    df["FB%"] = (df["FlyBalls"] / (df["BF"]-df["SO"]-df["BB"]-df["HBP"]) * 100).round(2)
    df["GB%"] = (df["GroundBalls"] / (df["BF"]-df["SO"]-df["BB"]-df["HBP"]) * 100).round(2)
    df["HHB%"] = (df["HardHitBalls"] / (df["BF"]-df["SO"]-df["BB"]-df["HBP"]) * 100).round(2)
    df["WEAK%"] = (df["WeakContact"] / (df["BF"]-df["SO"]-df["BB"]-df["HBP"]) * 100).round(2)
    df["<3%"] = (df["Under3Pitches"] / df["BF"] * 100).round(2)

    # SB%
    df["SB%"] = np.where(
        (df["SB"] + df["CS"]) > 0,
        (df["SB"] / (df["SB"] + df["CS"]) * 100).round(1),
        0
    )

    # BAA = H / (BF - BB - HBP)
    df["BAA"] = np.where(
        (df["BF"] - df["BB"] - df["HBP"]) > 0,
        (df["H"] / (df["BF"] - df["BB"] - df["HBP"])).round(3),
        0
    )

    # BABIP = (H - HR) / (BF - K - HR - BB - HBP)
    df["BABIP"] = np.where(
        (df["BF"] - df["SO"] - df["HR"] - df["BB"] - df["HBP"]) > 0,
        ((df["H"] - df["HR"]) / (df["BF"] - df["SO"] - df["HR"] - df["BB"] - df["HBP"])).round(3),
        0
    )

    # BA/RISP: leave as 0 unless calculated separately from another dataset
    if "BA/RISP" not in df.columns:
        df["BA/RISP"] = 0.000

    # Reformat column names and fill missing ones
    for col in columns_to_keep:
        if col not in df.columns:
            df[col] = 0

    # ==== Final cleanup ====
    df = df[columns_to_keep].copy()
    df = df.round(3)
    df = df.fillna(0)

    return df

